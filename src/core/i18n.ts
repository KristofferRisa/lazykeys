export type MessageKey = keyof typeof defaultMessages;
export type Messages = Record<MessageKey, string>;

/** What `messages` accepts: any subset of the defaults, plus plugins' own keys. */
export type MessageOverrides = Partial<Messages> & Record<string, string>;

export type Translate = (key: MessageKey | (string & {}), vars?: Record<string, string | number>) => string;

export function createTranslator(overrides: MessageOverrides = {}): Translate {
  const table: Record<string, string> = { ...defaultMessages, ...overrides };
  return (key, vars) => {
    const template = table[key] ?? key;
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
      Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole,
    );
  };
}
